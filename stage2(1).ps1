# =====================================================================
# stage2.ps1 — БЕЗОПАСНЫЙ скрипт второй стадии для стенда BadUSB-исследования
# =====================================================================
# НИЧЕГО не читает и не расшифровывает: не обращается к браузерам, к файлам
# профиля, к реестру и к сети (кроме факта собственной загрузки).
# Только генерирует фейковые записи и пишет два файла на рабочий стол.
#
# Зачем: у синей команды должны быть те же артефакты для детекции и отчётов,
# что и у настоящего инфорстилера (скачанный .ps1 в %TEMP%, новый файл
# "паролей" на рабочем столе), но с СИМУЛИРОВАННЫМИ данными.
# Реальную технику инфорстилеров описываешь в главе "Модель угроз" словами
# со ссылками на источники — без кода. Это стандартная этика red team стендов
# (по тому же принципу работает EICAR-тестовая строка в антивирусах).
# =====================================================================

$ErrorActionPreference = 'Stop'
$desktop = [Environment]::GetFolderPath('Desktop')
$stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'

# 1) Маркер выполнения stage2
"[$stamp] stage2 executed on $env:COMPUTERNAME (SIMULATION, no real data touched)" |
    Out-File -FilePath "$desktop\badusb_stage2_marker.txt" -Encoding utf8

# 2) СИМУЛИРОВАННЫЙ "дамп паролей" — все записи сгенерированы прямо здесь,
#    к реальным данным доступа нет. Формат как у настоящих дампов,
#    чтобы эксперименты и скриншоты выглядели реалистично.
$chars = (48..57) + (65..90) + (97..122)   # 0-9 A-Z a-z
$fake = foreach ($i in 1..5) {
    $user = "sim_user{0:D2}" -f $i
    $pass = -join ($chars | Get-Random -Count 12 | ForEach-Object { [char]$_ })
    [pscustomobject]@{
        url      = "https://simulated.invalid/$user"
        username = $user
        password = $pass
        note     = 'FAKE DATA - generated by stage2.ps1 for detection research'
    }
}
$fake | Format-Table -AutoSize | Out-String |
    Out-File -FilePath "$desktop\badusb_SIMULATED_credentials.txt" -Encoding utf8

Write-Host '[SIMULATION] stage2 done. Files on desktop contain FAKE data only.' -ForegroundColor Yellow
